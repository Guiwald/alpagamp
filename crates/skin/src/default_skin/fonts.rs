/// Largeur d'un glyphe de la police 4x5.
pub fn small_glyph_width(c: char) -> i32 {
    small(c).first().map(|r| r.len() as i32).unwrap_or(3)
}

/// Écrit un texte en police 4x5 avec 1 px d'espace (pour les titres dessinés dans le métal).
pub fn small_text(img: &mut Image, x: i32, y: i32, text: &str, c: u32) -> i32 {
    let mut cx = x;
    for ch in text.chars() {
        if ch == ' ' {
            cx += 3;
            continue;
        }
        glyph(img, cx, y, small(ch), c);
        cx += small_glyph_width(ch) + 1;
    }
    cx - x - 1
}

/// Largeur d'un texte en police 4x5.
pub fn small_text_width(text: &str) -> i32 {
    let mut w = 0;
    for ch in text.chars() {
        w += if ch == ' ' { 3 } else { small_glyph_width(ch) + 1 };
    }
    (w - 1).max(0)
}
